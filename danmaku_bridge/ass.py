"""把弹幕数据渲染成 .ass 字幕文件。

不依赖任何播放器：输出的是通用 ASS 字幕，交给 Jellyfin / Emby / Plex / VLC / mpv /
PotPlayer 等现成播放端加载即可。本工具本身不播放视频。
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Dict, Iterable, List, Tuple

MODE_SCROLL = 1
MODE_BOTTOM = 4
MODE_TOP = 5


@dataclass
class Comment:
    seconds: float
    mode: int
    color: int          # 0xRRGGBB
    text: str


def parse_comment(item: Dict[str, str]) -> Comment | None:
    """解析开放网络返回的单条弹幕（p = time,mode,color,uid）。"""
    try:
        parts = str(item.get("p", "")).split(",")
        seconds = float(parts[0])
        mode = int(float(parts[1])) if len(parts) > 1 else MODE_SCROLL
        color = int(float(parts[2])) if len(parts) > 2 else 0xFFFFFF
        text = str(item.get("m", "")).strip()
    except (ValueError, IndexError):
        return None
    if not text or seconds < 0:
        return None
    return Comment(seconds=seconds, mode=mode, color=color & 0xFFFFFF, text=text)


def _esc(text: str) -> str:
    """ASS 只把 {} 当控制符，换行会破坏单行结构，这里统一清洗。"""
    return (
        text.replace("\\", "\\\\")
        .replace("{", "(")
        .replace("}", ")")
        .replace("\r", " ")
        .replace("\n", " ")
    )


def _ass_color(rgb: int, alpha: int = 0) -> str:
    r = (rgb >> 16) & 0xFF
    g = (rgb >> 8) & 0xFF
    b = rgb & 0xFF
    return f"&H{alpha:02X}{b:02X}{g:02X}{r:02X}"


def _ts(seconds: float) -> str:
    if seconds < 0:
        seconds = 0
    cs = int(round(seconds * 100))
    h, cs = divmod(cs, 360000)
    m, cs = divmod(cs, 6000)
    s, cs = divmod(cs, 100)
    return f"{h:d}:{m:02d}:{s:02d}.{cs:02d}"


def _text_width(text: str, font_size: int) -> float:
    """粗略估算文本像素宽度：中日韩字符按 1 个字号，其余按 0.55。"""
    width = 0.0
    for ch in text:
        width += font_size * (1.0 if ord(ch) > 0x2E80 else 0.55)
    return width


def build_ass(
    comments: Iterable[Comment],
    play_res_x: int = 1920,
    play_res_y: int = 1080,
    font_name: str = "Microsoft YaHei",
    scroll_seconds: float = 9.0,
    max_comments: int = 3000,
    font_size: int | None = None,
) -> Tuple[str, int]:
    """生成 ASS 文本，返回 (内容, 实际写入条数)。"""
    font_size = font_size or max(18, int(play_res_y * 0.045))
    lane_height = font_size * 1.35
    margin = max(8, int(play_res_y * 0.02))
    lanes = max(1, int((play_res_y - margin * 2) // lane_height) - 1)

    items: List[Comment] = sorted(comments, key=lambda c: c.seconds)[:max_comments]

    header = f"""[Script Info]
; Generated by DanmakuBridge
; https://github.com/  (项目仓库)
ScriptType: v4.00+
PlayResX: {play_res_x}
PlayResY: {play_res_y}
WrapStyle: 2
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,{font_name},{font_size},&H00FFFFFF,&H00FFFFFF,&H00000000,&H64000000,-1,0,0,0,100,100,0,0,1,{max(2, font_size // 16)},{max(1, font_size // 24)},7,0,0,0,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

    lines: List[str] = []
    lane_cursor: List[float] = [0.0] * lanes
    seen = set()

    for c in items:
        key = (round(c.seconds, 2), c.text)
        if key in seen:
            continue
        seen.add(key)

        color = _ass_color(c.color)
        text = _esc(c.text)
        width = _text_width(text, font_size)
        duration = max(4.0, scroll_seconds * (play_res_x + width) / play_res_x)

        if c.mode in (MODE_TOP, MODE_BOTTOM):
            y = margin + font_size if c.mode == MODE_TOP else play_res_y - margin - font_size
            align = 8 if c.mode == MODE_TOP else 2
            effect = f"{{\\an{align}\\pos({play_res_x // 2},{y})\\c{color}\\bord{max(2, font_size // 16)}}}"
            lines.append(
                f"Dialogue: 0,{_ts(c.seconds)},{_ts(c.seconds + 4.0)},Default,,0,0,0,,{effect}{text}"
            )
            continue

        # 滚动弹幕：找一条空闲轨道，避免同屏重叠
        lane = _pick_lane(lane_cursor, c.seconds)
        y = int(margin + lane * lane_height + font_size)
        x1 = play_res_x + 10
        x2 = int(-width - 10)
        effect = (
            f"{{\\an7\\move({x1},{y},{x2},{y},0,{int(duration * 1000)})"
            f"\\c{color}\\bord{max(2, font_size // 16)}}}"
        )
        lines.append(
            f"Dialogue: 0,{_ts(c.seconds)},{_ts(c.seconds + duration)},Default,,0,0,0,,{effect}{text}"
        )

    return header + "\n".join(lines) + "\n", len(lines)


def _pick_lane(cursor: List[float], seconds: float) -> int:
    """轨道占用时间按「弹幕离开屏幕右侧所需时间」估算，取最早空闲的轨道。"""
    best = 0
    best_time = math.inf
    for idx, free_at in enumerate(cursor):
        if free_at < best_time:
            best_time = free_at
            best = idx
    # 下一条弹幕至少间隔 0.4 秒进入同一轨道
    cursor[best] = max(cursor[best], seconds) + 0.4
    return best


def load_comments(payload: Dict) -> List[Comment]:
    raw = payload.get("comments")
    if not isinstance(raw, list):
        return []
    out = []
    for item in raw:
        if isinstance(item, dict):
            parsed = parse_comment(item)
            if parsed:
                out.append(parsed)
    return out
